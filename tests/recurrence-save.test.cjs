const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../app.js'),'utf8');
const context={state:{events:[]},pendingAction:null,parseDate:s=>new Date(s+'T00:00:00'),dateStr:d=>`${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`,
 clearGoogleEventAppearance(){},queueGoogleRecurringOp(){return false},rememberGoogleDeletes(){},toast(){},closeDrawers(){},render(){},$:()=>({classList:{add(){}}})};
vm.createContext(context);
for(const name of ['commit','updateRecurringOccurrences','createOccurrences'])vm.runInContext(source.split('\n').find(line=>line.startsWith(`function ${name}(`)),context);
const original={id:'original',title:'연습',date:'2026-10-12',start:'19:00',end:'20:00',repeat:'none',seriesId:'',labelId:'mine',googleEventId:'remote-original',source:'google'};
const unrelated={id:'other',title:'다른 일정',date:'2026-10-20'};
context.state.events=[{...original},unrelated];
context.pendingAction={type:'update',data:{...original,repeat:'weekly',repeatDays:[1],repeatEndType:'never',repeatEndValue:''}};
context.commit('single');
const events=context.state.events.filter(e=>e.id!=='other');
assert.equal(events.length,120);
assert.equal(events[0].id,'original');
assert.equal(events[0].googleEventId,'remote-original');
assert.equal(events[1].date,'2026-10-19');
assert(events.every(e=>e.repeat==='weekly'&&new Date(e.date+'T00:00:00').getDay()===1));
assert(events.slice(1).every(e=>!e.googleEventId&&e.source==='local'));
assert.equal(new Set(events.map(e=>e.id)).size,120);
assert.equal(context.state.events.find(e=>e.id==='other'),unrelated);
context.state.events=[{...original}];
context.pendingAction={type:'update',data:{...original,title:'변경'}};
context.commit('single');
assert.equal(context.state.events.length,1);
assert.equal(context.state.events[0].title,'변경');
context.state.events=[{...original,seriesId:'existing-series',repeat:'weekly'}];
context.pendingAction={type:'update',data:{...context.state.events[0],title:'이번만 변경'}};
context.commit('single');
assert.equal(context.state.events[0].repeat,'none');
assert.equal(context.state.events[0].seriesId,'');
context.state.events=[];
context.createOccurrences({...original,repeat:'weekly',repeatDays:[1],repeatEndType:'date',repeatEndValue:'2026-10-26'});
assert.equal(context.state.events.length,3);
console.log('PASS: single-to-weekly save, next Monday, unique identities, Google identity isolation, unrelated events, one-off edits, end date');

